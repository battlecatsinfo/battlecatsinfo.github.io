/**
 * 逐字归一；表外的字符原样保留。
 * @param {string} text - 待归一化文本。
 * @returns {string} 归一化后的文本。
 */
export function toTw(text) {
	if (!text) return text;
	let out = '';
	for (const ch of text)
		out += MAP[ch] || ch;
	return out;
}
