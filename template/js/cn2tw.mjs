/**
 * 逐字把简体转成繁体；非汉字与本身已是繁体的字符原样保留。
 * @param {string} text - 待转换文本。
 * @returns {string} 转换后的文本。
 */
export function toTw(text) {
	if (!text) return text;
	let out = '';
	for (const ch of text)
		out += MAP[ch] || ch;
	return out;
}

/**
 * 搜索时可用的一组候选写法：原文 + 繁体归一化结果（去重）。
 * 保留原文是为了避免数据本身写作简体形状时漏搜。
 * @param {string} text - 用户输入。
 * @returns {string[]} 候选写法。
 */
export function searchVariants(text) {
	const tw = toTw(text);
	return tw === text ? [text] : [text, tw];
}
